"""Generate a four-phase lineage that replays the hand-tuned Qwen3-4B schedule for another model, seed or recipe.

Each phase copies configs/experiments/qwen3-4b-v1-handtuned/phase_<x>.yaml and changes only the model, the seed, the
warm start and any KEY=VALUE overrides given on the command line. Phase x+1 always starts from the final step of
phase x, so no checkpoint is chosen by hand (the hand-tuned lineage used validation-selected steps 40 / 90 / 90).

  phase a  40 steps from the base model, single-candidate demo prompt
  phase b  90 steps, multi-candidate demo prompt
  phase c  90 steps, hint cycle 1/2 -> 1/4 -> 0 at steps 0 / 30 / 60
  phase d  80 steps, hint cycle at steps 0 / 25 / 50, 5-step LR warmup

Recipe v2 is the override set kl_coef=0 min_kl_coef=0 max_kl_coef=0 "hint_schedule=''" train_nocorrect_groups=false
max_grad_norm=1.0 shuffle_minibatches=true; the zero-shot arms add prompt_style=r1zero_tool.

usage: python scripts/make_lineage_configs.py NAME MODEL SEED [KEY=VALUE ...]
writes configs/experiments/NAME/phase_{a,b,c,d}.yaml; the run id of phase x is NAME-x.
"""
import os
import sys
import textwrap

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "configs", "experiments", "qwen3-4b-v1-handtuned")
PHASES = [("a", 40), ("b", 90), ("c", 90), ("d", 80)]
NOT_REPORTED = {"model", "seed", "total_steps", "checkpoint_every", "checkpoint_timer", "init_lora"}


def header(name, phase, cfg, src):
    diff = [k for k in cfg if k not in NOT_REPORTED and cfg.get(k) != src.get(k)]
    diff += [k for k in src if k not in cfg and k not in NOT_REPORTED]
    start = "the base model" if phase == "a" else f"the final step of phase {chr(ord(phase) - 1)}"
    text = [f"{name}, phase {phase}: replay of qwen3-4b-v1-handtuned/phase_{phase}.yaml from {start}.",
            "Generated by scripts/make_lineage_configs.py. Differs from the source in: model, seed"
            + "".join(", " + k for k in diff) + "."]
    return "".join("# " + w + "\n" for t in text for w in textwrap.wrap(t, 112))


def main(argv):
    name, model, seed, *extra = argv
    overrides = {k: yaml.safe_load(v) for k, v in (kv.split("=", 1) for kv in extra)}
    out_dir = os.path.join(ROOT, "configs", "experiments", name)
    os.makedirs(out_dir, exist_ok=True)
    prev = None
    for phase, steps in PHASES:
        src = yaml.safe_load(open(os.path.join(SOURCE, f"phase_{phase}.yaml")))
        cfg = dict(src, model=model, seed=int(seed), total_steps=steps, checkpoint_every=2, checkpoint_timer=300)
        cfg.pop("init_lora", None)
        if prev:
            cfg["init_lora"] = f"baselines/{prev}_final"
        cfg.update(overrides)
        path = os.path.join(out_dir, f"phase_{phase}.yaml")
        with open(path, "w") as f:
            f.write(header(name, phase, cfg, src))
            yaml.safe_dump(cfg, f, sort_keys=False)
        print(f"{name}-{phase}={os.path.relpath(path, ROOT)}")
        prev = f"{name}-{phase}"


if __name__ == "__main__":
    main(sys.argv[1:])
